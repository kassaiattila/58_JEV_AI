import { act, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { beforeEach, describe, expect, it, vi } from "vitest";
import { api, ApiError, setActor } from "../api";
import { setLanguage } from "../i18n";
import { codePointSlice, elementKey, type NativeItemResult, type NativeSourcePage } from "../native";
import { ItemReview } from "../views/ReviewWorkspace";
import { defaultResultTable } from "../views/ResultStage";
import { clearDraft, draftKey, getDraft, hydrateDrafts, resetDrafts, setNativeField, setNativeSources, settleNativeDraft } from "./drafts";
import { NativeFactPanel, nativeSaveBody } from "./NativeFactPanel";
import { loadNativeSource } from "./NativeReview";
